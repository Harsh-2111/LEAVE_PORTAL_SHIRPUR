<?php
header('Content-Type: application/json; charset=utf-8');
require_once __DIR__ . '/db.php';
require_once __DIR__ . '/auth.php';
require_once __DIR__ . '/notifications.php';

$user = requireRole(['student', 'warden']);

try {
    $tableCheck = $pdo->prepare("SELECT 1 FROM information_schema.tables WHERE table_schema = ? AND table_name = 'notifications'");
    $tableCheck->execute([DB_DRIVER === 'pgsql' ? 'public' : DB_NAME]);
    if (!$tableCheck->fetchColumn()) {
        $createNotifications = DB_DRIVER === 'pgsql'
            ? "CREATE TABLE IF NOT EXISTS public.notifications (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE, leave_id BIGINT REFERENCES public.leave_requests(id) ON DELETE CASCADE ON UPDATE CASCADE, type VARCHAR(40) NOT NULL, title VARCHAR(150) NOT NULL, message TEXT NOT NULL, link VARCHAR(255), read_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())"
            : "CREATE TABLE IF NOT EXISTS notifications (id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, leave_id BIGINT UNSIGNED NULL, type VARCHAR(40) NOT NULL, title VARCHAR(150) NOT NULL, message TEXT NOT NULL, link VARCHAR(255), read_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, CONSTRAINT fk_notifications_user_runtime FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE, CONSTRAINT fk_notifications_leave_runtime FOREIGN KEY (leave_id) REFERENCES leave_requests(id) ON DELETE CASCADE ON UPDATE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci";
        $pdo->exec($createNotifications);
        $pdo->exec(DB_DRIVER === 'pgsql'
            ? 'CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON public.notifications (user_id, created_at DESC)'
            : 'CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON notifications (user_id, created_at)');
        $pdo->exec(DB_DRIVER === 'pgsql'
            ? 'CREATE INDEX IF NOT EXISTS idx_notifications_unread ON public.notifications (user_id, read_at)'
            : 'CREATE INDEX IF NOT EXISTS idx_notifications_unread ON notifications (user_id, read_at)');
    }
} catch (Throwable $tableError) {
    http_response_code(500);
    echo json_encode(['success' => false, 'message' => 'Notification storage is unavailable.']);
    exit;
}

if ($_SERVER['REQUEST_METHOD'] === 'POST') {
    requireCsrfToken();
    $action = trim((string)($_POST['action'] ?? ''));
    if ($action === 'clear') {
        $delete = $pdo->prepare('DELETE FROM notifications WHERE user_id = ?');
        $delete->execute([(int)$user['id']]);
        echo json_encode(['success' => true]);
        exit;
    }
    $id = (int)($_POST['notification_id'] ?? 0);
    if ($action === 'read' && $id > 0) {
        $update = $pdo->prepare('UPDATE notifications SET read_at = NOW() WHERE id = ? AND user_id = ? AND read_at IS NULL');
        $update->execute([$id, (int)$user['id']]);
    } elseif ($action === 'read_all') {
        $update = $pdo->prepare('UPDATE notifications SET read_at = NOW() WHERE user_id = ? AND read_at IS NULL');
        $update->execute([(int)$user['id']]);
    } else {
        http_response_code(400);
        echo json_encode(['success' => false, 'message' => 'Unknown notification action.']);
        exit;
    }
    echo json_encode(['success' => true]);
    exit;
}

if ($_SERVER['REQUEST_METHOD'] !== 'GET') {
    http_response_code(405);
    echo json_encode(['success' => false, 'message' => 'Only GET or POST requests are allowed.']);
    exit;
}
$stmt = $pdo->prepare('SELECT id, leave_id, type, title, message, link, read_at, created_at FROM notifications WHERE user_id = ? ORDER BY created_at DESC, id DESC LIMIT 50');
$stmt->execute([(int)$user['id']]);
$items = $stmt->fetchAll();
$count = $pdo->prepare('SELECT COUNT(*) FROM notifications WHERE user_id = ? AND read_at IS NULL');
$count->execute([(int)$user['id']]);
$unread = (int)$count->fetchColumn();
echo json_encode(['success' => true, 'unread_count' => $unread, 'items' => $items]);
