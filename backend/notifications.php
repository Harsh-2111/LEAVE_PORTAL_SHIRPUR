<?php
function notificationRecipients(PDO $pdo, int $leaveId): array
{
    $stmt = $pdo->prepare('SELECT lr.sap_id, lr.hostel, s.gender FROM leave_requests lr INNER JOIN students s ON s.sap_id = lr.sap_id WHERE lr.id = ? LIMIT 1');
    $stmt->execute([$leaveId]);
    $leave = $stmt->fetch();
    if (!$leave) return [];

    $recipientIds = [];
    $student = $pdo->prepare('SELECT id FROM users WHERE login_id = ? AND role = ? LIMIT 1');
    $student->execute([(string)$leave['sap_id'], 'student']);
    if ($row = $student->fetch()) $recipientIds[] = (int)$row['id'];

    $warden = $pdo->prepare('SELECT id FROM users WHERE role = ? AND warden_gender = ? AND warden_hostel = ? AND is_active = TRUE');
    $warden->execute(['warden', (string)$leave['gender'], (string)$leave['hostel']]);
    foreach ($warden->fetchAll() as $row) $recipientIds[] = (int)$row['id'];

    return array_values(array_unique($recipientIds));
}

function notifyStudent(PDO $pdo, int $leaveId, string $type, string $title, string $message): void
{
    $stmt = $pdo->prepare('SELECT lr.sap_id FROM leave_requests lr WHERE lr.id = ? LIMIT 1');
    $stmt->execute([$leaveId]);
    if (!$sapId = $stmt->fetchColumn()) return;
    $student = $pdo->prepare('SELECT id FROM users WHERE login_id = ? AND role = ? LIMIT 1');
    $student->execute([(string)$sapId, 'student']);
    if ($row = $student->fetch()) insertNotifications($pdo, [(int)$row['id']], $leaveId, $type, $title, $message);
}

function notifyWarden(PDO $pdo, int $leaveId, string $type, string $title, string $message): void
{
    $recipients = notificationRecipients($pdo, $leaveId);
    $stmt = $pdo->prepare('SELECT lr.sap_id FROM leave_requests lr WHERE lr.id = ? LIMIT 1');
    $stmt->execute([$leaveId]);
    $sapId = $stmt->fetchColumn();
    $student = $pdo->prepare('SELECT id FROM users WHERE login_id = ? AND role = ? LIMIT 1');
    $student->execute([(string)$sapId, 'student']);
    $studentId = $student->fetchColumn();
    if ($studentId !== false) $recipients = array_values(array_diff($recipients, [(int)$studentId]));
    insertNotifications($pdo, $recipients, $leaveId, $type, $title, $message);
}

function notifyLeave(PDO $pdo, int $leaveId, string $type, string $title, string $message): void
{
    insertNotifications($pdo, notificationRecipients($pdo, $leaveId), $leaveId, $type, $title, $message);
}

function ensureNotificationsTable(PDO $pdo): void
{
    static $tableReady = false;
    if ($tableReady) return;

    $tableCheck = $pdo->prepare("SELECT 1 FROM information_schema.tables WHERE table_schema = ? AND table_name = 'notifications' LIMIT 1");
    $tableCheck->execute([DB_DRIVER === 'pgsql' ? 'public' : DB_NAME]);
    if ($tableCheck->fetchColumn()) {
        $tableReady = true;
        return;
    }

    if (DB_DRIVER === 'pgsql') {
        $pdo->exec("CREATE TABLE IF NOT EXISTS public.notifications (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES public.users(id) ON DELETE CASCADE ON UPDATE CASCADE, leave_id BIGINT REFERENCES public.leave_requests(id) ON DELETE CASCADE ON UPDATE CASCADE, type VARCHAR(40) NOT NULL, title VARCHAR(150) NOT NULL, message TEXT NOT NULL, link VARCHAR(255), read_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW())");
        $pdo->exec('CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON public.notifications (user_id, created_at DESC)');
        $pdo->exec('CREATE INDEX IF NOT EXISTS idx_notifications_unread ON public.notifications (user_id, read_at)');
        $tableReady = true;
        return;
    }
    $pdo->exec("CREATE TABLE IF NOT EXISTS notifications (id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NOT NULL, leave_id BIGINT UNSIGNED NULL, type VARCHAR(40) NOT NULL, title VARCHAR(150) NOT NULL, message TEXT NOT NULL, link VARCHAR(255), read_at DATETIME NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, KEY idx_notifications_user_created (user_id, created_at), KEY idx_notifications_unread (user_id, read_at), CONSTRAINT fk_notifications_user_runtime FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE ON UPDATE CASCADE, CONSTRAINT fk_notifications_leave_runtime FOREIGN KEY (leave_id) REFERENCES leave_requests(id) ON DELETE CASCADE ON UPDATE CASCADE) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci");
    $tableReady = true;
}

function insertNotifications(PDO $pdo, array $recipientIds, int $leaveId, string $type, string $title, string $message): void
{
    $recipientIds = array_values(array_unique(array_filter(
        $recipientIds,
        static fn($recipientId): bool => (int)$recipientId > 0
    )));
    if (!$recipientIds) return;
    ensureNotificationsTable($pdo);
    $values = implode(', ', array_fill(0, count($recipientIds), '(?, ?, ?, ?, ?, ?, NOW())'));
    $sql = DB_DRIVER === 'pgsql'
        ? 'INSERT INTO public.notifications (user_id, leave_id, type, title, message, link, created_at) VALUES ' . $values
        : 'INSERT INTO notifications (user_id, leave_id, type, title, message, link, created_at) VALUES ' . $values;
    $params = [];
    foreach ($recipientIds as $recipientId) {
        array_push($params, (int)$recipientId, $leaveId, $type, $title, $message, '#leave-' . $leaveId);
    }
    $pdo->prepare($sql)->execute($params);
}
