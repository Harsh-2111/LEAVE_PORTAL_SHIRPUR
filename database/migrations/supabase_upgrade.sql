CREATE TABLE IF NOT EXISTS public.leave_policies (
  hostel VARCHAR(40) PRIMARY KEY
    CHECK (hostel IN ('BOYS HOSTEL 1', 'NEW BOYS HOSTEL', 'NEW GIRLS HOSTEL', 'OLD GIRLS HOSTEL')),
  max_leave_days INTEGER CHECK (max_leave_days IS NULL OR max_leave_days > 0),
  max_requests_per_month INTEGER CHECK (max_requests_per_month IS NULL OR max_requests_per_month > 0),
  minimum_notice_hours INTEGER CHECK (minimum_notice_hours IS NULL OR minimum_notice_hours >= 0),
  updated_by BIGINT REFERENCES public.users (id) ON DELETE SET NULL ON UPDATE CASCADE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.announcements (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title VARCHAR(150) NOT NULL,
  body TEXT NOT NULL,
  target_role VARCHAR(20) NOT NULL DEFAULT 'all'
    CHECK (target_role IN ('all', 'student', 'warden')),
  target_hostel VARCHAR(40)
    CHECK (target_hostel IS NULL OR target_hostel IN ('BOYS HOSTEL 1', 'NEW BOYS HOSTEL', 'NEW GIRLS HOSTEL', 'OLD GIRLS HOSTEL')),
  expires_at TIMESTAMPTZ,
  created_by BIGINT NOT NULL REFERENCES public.users (id) ON DELETE RESTRICT ON UPDATE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_announcements_active ON public.announcements (created_at DESC, expires_at);
CREATE INDEX IF NOT EXISTS idx_leave_policies_hostel ON public.leave_policies (hostel);

CREATE TABLE IF NOT EXISTS public.notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE ON UPDATE CASCADE,
  leave_id BIGINT REFERENCES public.leave_requests (id) ON DELETE CASCADE ON UPDATE CASCADE,
  type VARCHAR(40) NOT NULL,
  title VARCHAR(150) NOT NULL,
  message TEXT NOT NULL,
  link VARCHAR(255),
  read_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_notifications_user_created ON public.notifications (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_unread ON public.notifications (user_id, read_at);


